const pass = (_request, _response, next) => next();
const invoke = (router, path, method, request) =>
  new Promise((resolve, reject) => {
    const layer = router.stack.find(
      (candidate) => candidate.route?.path === path && candidate.route.methods[method],
    );
    assert.ok(layer);
    const handlers = layer.route.stack.map(({ handle }) => handle);
    const response = {
      statusCode: 200,
      status(value) {
        this.statusCode = value;
        return this;
      },
      json(body) {
        resolve({ status: this.statusCode, body });
      },
    };
    let index = 0;
    const next = (error) => {
      if (error) return reject(error);
      handlers[index++]?.(request, response, next);
    };
    next();
  });

test('the shared auth fixture is accepted unchanged by the route contract and OpenAPI', async () => {
  const router = createAuthRouter({
    credentials: {
      register: async () => AUTH_SESSION_FIXTURE,
      login: async () => AUTH_SESSION_FIXTURE,
    },
    providers: {
      loginWithGoogle: async () => AUTH_SESSION_FIXTURE,
      loginWithApple: async () => AUTH_SESSION_FIXTURE,
    },
    microsoft: {
      createAttempt: async () => ({}),
      login: async () => ({ status: 'authenticated', session: AUTH_SESSION_FIXTURE }),
      sendVerificationEmail: async () => ({}),
      confirmVerificationEmail: async () => AUTH_SESSION_FIXTURE,
    },
    sessions: { refresh: async () => ({}), revoke: async () => undefined },
    accountDeletion: { deleteAccount: async () => ({}) },
    authenticate: pass,
    rateLimitRegistration: pass,
    rateLimitMicrosoftAttempt: pass,
    rateLimitMicrosoftEmail: pass,
    rateLimitMicrosoftConfirmation: pass,
  });
  const result = await invoke(router, '/register', 'post', {
    body: { email: 'person@example.com', password: 'secret' },
    headers: { 'x-timezone': 'America/Toronto' },
  });
  assert.deepEqual(result, { status: 201, body: AUTH_SESSION_FIXTURE });
  assert.deepEqual(openApiSpec.components.schemas.AuthSession.example, AUTH_SESSION_FIXTURE);
});

test('receipt and export fixtures match their canonical mappers and OpenAPI schemas', () => {
  const source = RECEIPT_PAGE_FIXTURE.items[0];
  const receipt = new Receipt(
    source.userId,
    source.items,
    source.amountSpent,
    source.receiptType,
    source.restaurantName,
    new Date(source.orderDate),
    source.dataSource,
    undefined,
    undefined,
    source.id,
  );
  assert.deepEqual(mapReceiptPageResponse([receipt], 1, 1, 20), RECEIPT_PAGE_FIXTURE);
  assert.deepEqual(openApiSpec.components.schemas.ReceiptPage.example, RECEIPT_PAGE_FIXTURE);
  assert.deepEqual(openApiSpec.components.schemas.CsvImportResult.example, CSV_IMPORT_FIXTURE);
});

test('the canonical error fixture is generated by the envelope builder and legacy schemas are absent', () => {
  const envelope = buildErrorEnvelopeV1(
    {
      originalUrl: '/auth/register',
      method: 'POST',
      requestId: ERROR_ENVELOPE_FIXTURE.error.requestId,
    },
    400,
    'VALIDATION_ERROR',
    ERROR_ENVELOPE_FIXTURE.error.message,
    {
      details: ERROR_ENVELOPE_FIXTURE.error.details,
      now: new Date(ERROR_ENVELOPE_FIXTURE.error.timestamp),
    },
  );
  assert.deepEqual(envelope, ERROR_ENVELOPE_FIXTURE);
  assert.equal(openApiSpec.components.schemas.CreateUserRequest, undefined);
  assert.equal(openApiSpec.paths['/users/create'], undefined);
  assert.ok(openApiSpec.paths['/auth/register']);
});
